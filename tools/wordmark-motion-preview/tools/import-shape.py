#!/usr/bin/env python3
"""Import an edited glyph SVG into the animation's editable path data.
Uses only Python's standard library. Run from any folder:
  python3 tools/import-shape.py wide editable-shapes/wide.svg
Preserve path IDs and the font-space group. Supports M/L/H/V/C/S/Q/T/Z and
translate/scale/rotate/matrix transforms. Rejects arc paths or mismatched topology
rather than silently distorting the logo. Writes the installed assets/js/wordmark-shapes.js directly.
"""
from pathlib import Path
import argparse,json,re,math,xml.etree.ElementTree as E
ROOT=Path(__file__).resolve().parents[1]
PARTS=['body','leftDot','rightDot']
I=(1,0,0,1,0,0)
def mul(a,b):
 return (a[0]*b[0]+a[2]*b[1],a[1]*b[0]+a[3]*b[1],a[0]*b[2]+a[2]*b[3],a[1]*b[2]+a[3]*b[3],a[0]*b[4]+a[2]*b[5]+a[4],a[1]*b[4]+a[3]*b[5]+a[5])
def matrix(s):
 out=I
 for name,raw in re.findall(r'([A-Za-z]+)\s*\(([^)]*)\)',s or ''):
  n=[float(v) for v in re.findall(r'[-+]?(?:\d*\.\d+|\d+\.?\d*)(?:[eE][-+]?\d+)?',raw)]
  if name=='translate':m=(1,0,0,1,n[0],n[1] if len(n)>1 else 0)
  elif name=='scale':m=(n[0],0,0,n[-1],0,0)
  elif name=='matrix' and len(n)==6:m=tuple(n)
  elif name=='rotate':
   r=math.radians(n[0]);m=(math.cos(r),math.sin(r),-math.sin(r),math.cos(r),0,0)
   if len(n)==3:m=mul(mul((1,0,0,1,n[1],n[2]),m),(1,0,0,1,-n[1],-n[2]))
  else:raise ValueError('Unsupported transform: '+name)
  out=mul(out,m)
 return out

def parse(d):
 tokens=re.findall(r'[A-Za-z]|[-+]?(?:\d*\.\d+|\d+\.?\d*)(?:[eE][-+]?\d+)?',d)
 out=[];i=0;cmd=None;cur=(0,0);start=cur;prev_c=None;prev_q=None;previous=None
 counts={'M':2,'L':2,'H':1,'V':1,'C':6,'S':4,'Q':4,'T':2,'Z':0}
 while i<len(tokens):
  if tokens[i].isalpha():cmd=tokens[i];i+=1
  if cmd is None or cmd.upper() not in counts:raise ValueError('Use editable M/L/C paths; arc paths require conversion first.')
  op=cmd.upper();rel=cmd.islower();count=counts[op]
  if op=='Z':out.append(['Z']);cur=start;cmd=None;prev_c=prev_q=None;previous='Z';continue
  vals=[float(v) for v in tokens[i:i+count]]
  if len(vals)!=count:raise ValueError('Incomplete path command')
  i+=count
  point=lambda x,y:(x+cur[0],y+cur[1]) if rel else (x,y)
  if op in ('M','L'):
   end=point(*vals);out.append([op,*end]);cur=end
   if op=='M':start=end;cmd='l' if rel else 'L'
  elif op=='H':cur=(vals[0]+cur[0] if rel else vals[0],cur[1]);out.append(['L',*cur])
  elif op=='V':cur=(cur[0],vals[0]+cur[1] if rel else vals[0]);out.append(['L',*cur])
  elif op in ('C','S'):
   if op=='C':a,b,end=[point(*vals[j:j+2]) for j in (0,2,4)]
   else:a=tuple(2*cur[j]-prev_c[j] for j in (0,1)) if previous in ('C','S') else cur;b=point(*vals[:2]);end=point(*vals[2:])
   out.append(['C',*a,*b,*end]);cur=end;prev_c=b
  elif op in ('Q','T'):
   if op=='Q':q=point(*vals[:2]);end=point(*vals[2:])
   else:q=tuple(2*cur[j]-prev_q[j] for j in (0,1)) if previous in ('Q','T') else cur;end=point(*vals)
   a=tuple(cur[j]+2/3*(q[j]-cur[j]) for j in (0,1));b=tuple(end[j]+2/3*(q[j]-end[j]) for j in (0,1))
   out.append(['C',*a,*b,*end]);cur=end;prev_q=q
  if op not in ('C','S'):prev_c=None
  if op not in ('Q','T'):prev_q=None
  previous=op
 return out

def load_svg(file):
 root=E.parse(file).getroot();parents={child:parent for parent in root.iter() for child in parent};out={}
 for part in PARTS:
  node=next((e for e in root.iter() if e.get('id')==part),None)
  if node is None:raise ValueError('Missing path ID: '+part)
  chain=[];n=node
  while n.get('id')!='font-space':
   chain.append(n);n=parents.get(n)
   if n is None:raise ValueError('Preserve the font-space group in the editable SVG.')
  m=I
  for e in reversed(chain):m=mul(m,matrix(e.get('transform')))
  ops=parse(node.get('d',''))
  for op in ops:
   for j in range(1,len(op),2):
    x,y=op[j:j+2];op[j]=round(m[0]*x+m[2]*y+m[4],9);op[j+1]=round(m[1]*x+m[3]*y+m[5],9)
  out[part]=ops
 return out

def main():
 ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('shape',choices=['original','smiley','wide']);ap.add_argument('svg',type=Path);a=ap.parse_args()
 source=ROOT/'editable-shapes/shapes.json';shapes=json.loads(source.read_text());new=load_svg(a.svg)
 for part in PARTS:
  expected=[(op[0],len(op)) for op in shapes[a.shape][part]];actual=[(op[0],len(op)) for op in new[part]]
  if expected!=actual:raise ValueError(part+' changed its number/type of commands. Edit existing points or normalise all three states together.')
 shapes[a.shape]=new
 source.write_text(json.dumps(shapes,indent=2)+'\n')
 (ROOT.parents[1]/'assets/js/wordmark-shapes.js').write_text('/* Editable SVG path data: body, leftDot, rightDot. Regenerated by tools/import-shape.py. */\nwindow.AK_WORDMARK_SHAPES = '+json.dumps(shapes,indent=2)+';\n')
 print('Updated',a.shape,'in editable-shapes/shapes.json and assets/wordmark-shapes.js. Advance its version query in all shared-navbar pages after editing.')
if __name__=='__main__':main()
